"use strict";
// Build a self-contained Obsidian plugin using only Node's built-in modules.
const fs = require("node:fs");
const path = require("node:path");
const entry = fs.readFileSync(path.join(__dirname, "entry.js"), "utf8");
const core = fs.readFileSync(path.join(__dirname, "lib", "importer.js"), "utf8");
const marker = 'require("./lib/importer.js")';
if (entry.split(marker).length !== 2) {
  throw new Error("entry.js must contain exactly one importer-core require.");
}
const bundledCore = [
  "(() => {",
  "  const module = { exports: {} };",
  "  const exports = module.exports;",
  "  // Bundled importer core: edit lib/importer.js, then run node build.cjs.",
  core,
  "  return module.exports;",
  "})()",
].join("\n");
const output = "// Generated by build.cjs. Edit entry.js or lib/importer.js, then rebuild.\n" + entry.replace(marker, bundledCore);
fs.writeFileSync(path.join(__dirname, "main.js"), output, "utf8");
console.log("Built self-contained main.js");
