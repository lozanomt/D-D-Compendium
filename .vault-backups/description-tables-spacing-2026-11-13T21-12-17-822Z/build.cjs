'use strict';
const fs=require('node:fs'),path=require('node:path');
let entry=fs.readFileSync(path.join(__dirname,'entry.js'),'utf8');
for(const name of ['importer','character-rules','character-sheet']) {
 const marker='require("./lib/'+name+'.js")';
 if(entry.split(marker).length!==2)throw Error('Expected one require for '+name);
 const source=fs.readFileSync(path.join(__dirname,'lib',name+'.js'),'utf8');
 entry=entry.replace(marker,()=>['(()=>{const module={exports:{}};const exports=module.exports;',source,'return module.exports;})()'].join('\n'));
}
fs.writeFileSync(path.join(__dirname,'main.js'),'// Generated by build.cjs. Edit entry.js or lib/ sources, then rebuild.\n'+entry);
console.log('Built self-contained main.js');
